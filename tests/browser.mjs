import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
fs.mkdirSync('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [], failed = [];
page.on('pageerror', e => errors.push(e.message));
page.on('response', r => { if (r.status() >= 400 && r.url().includes('127.0.0.1')) failed.push([r.status(), r.url()]); });
try {
  await page.goto('http://127.0.0.1:4173', { waitUntil: 'domcontentloaded' });
  await page.locator('.preloader').waitFor({ state: 'visible' });
  await page.mouse.wheel(0, 700);
  assert.equal(await page.evaluate(() => scrollY), 0);
  await page.waitForFunction(() => document.querySelector('main').dataset.transitioning === 'false');
  await page.waitForTimeout(200);
  await page.screenshot({ path: 'test-results/lavilla-preloader.png' });
  await page.locator('.preloader').waitFor({ state: 'detached', timeout: 10000 });
  await page.waitForTimeout(1700);
  assert.equal(await page.evaluate(() => document.body.style.position), '');
  assert.equal(await page.locator('#home video').count(), 1);
  assert.equal(await page.locator('#interior video').count(), 1);
  assert.equal(await page.locator('video').count(), 2);
  assert.equal(await page.getByRole('progressbar').count(), 0);
  assert.equal(await page.getByRole('button', { name: /play|pause|resume|replay/i }).count(), 0);
  assert.equal(await page.locator('video[controls]').count(), 0);
  assert.ok((await page.locator('#home video').getAttribute('src')).endsWith('lavilla-hero.mp4'));
  assert.ok((await page.locator('#interior video').getAttribute('src')).endsWith('lavilla-interior.mp4'));
  const geometry = await page.evaluate(() => { const a = document.querySelector('#home').getBoundingClientRect(), b = document.querySelector('#interior').getBoundingClientRect(); return { bottom: a.bottom, top: b.top } });
  assert.ok(geometry.top >= geometry.bottom - 1, 'Films must be separate, sequential sections');
  assert.equal(await page.locator('#home video').evaluate(v => v.playbackRate), .65);
  await page.waitForFunction(() => !document.querySelector('#home video').paused);
  await page.screenshot({ path: 'test-results/lavilla-home-desktop.png' });
  await page.getByRole('link', { name: 'Step inside', exact: true }).click();
  var beforeExit = await page.evaluate(() => scrollY);
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(() => scrollY), beforeExit, 'Next section waits for outgoing effect');
  await page.waitForFunction(() => document.querySelector('main').dataset.transitioning === 'false');
  await page.waitForTimeout(200);
  assert.equal(await page.evaluate(() => location.hash), '#interior');
  await page.waitForFunction(() => !document.querySelector('#interior video').paused);
  await page.waitForTimeout(1300);
  await page.screenshot({ path: 'test-results/lavilla-interior-desktop.png' });
  assert.ok(await page.locator('#home video').evaluate(v => v.paused), 'Offscreen film pauses');
  const interiorY = await page.evaluate(() => scrollY);
  await page.mouse.wheel(0, 900);
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(() => scrollY), interiorY, 'Interior follows the same gated scroll rule');
  await page.waitForFunction(() => document.querySelector('main').dataset.transitioning === 'false');
  await page.getByRole('link', { name: 'Collection', exact: true }).first().click();
  await page.waitForFunction(() => document.querySelector('main').dataset.transitioning === 'false');
  await page.waitForTimeout(200);
  await page.getByRole('button', { name: /VILLA SOL.*3 BED/ }).click();
  assert.equal(await page.evaluate(() => sessionStorage.getItem('lavilla.collection')), '2');
  await page.getByLabel('Average nightly rate').fill('500');
  await page.getByLabel('Annual occupancy').fill('80');
  await page.getByRole('link', { name: 'Contact', exact: true }).first().click();
  await page.waitForFunction(() => document.querySelector('main').dataset.transitioning === 'false');
  await page.waitForTimeout(200);
  await page.getByLabel('Full name', { exact: true }).fill('Final QA');
  await page.getByLabel('Email address', { exact: true }).fill('qa@example.com');
  await page.getByLabel('What are you looking for?').fill('A private two bedroom residence.');
  await page.getByRole('button', { name: 'Save private inquiry' }).click();
  assert.equal(await page.evaluate(() => JSON.parse(sessionStorage.getItem('lavilla.inquiries')).length), 1);
  await page.getByRole('button', { name: 'Discover LAVILLA', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Full name').fill('Final QA');
  await dialog.getByLabel('Email address').fill('qa@example.com');
  const pending = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download overview' }).click();
  assert.equal((await pending).suggestedFilename(), 'LAVILLA-Residence-Overview.html');
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const start = Date.now(); await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.preloader').waitFor({ state: 'detached', timeout: 6000 });
  const reducedLoadMs = Date.now() - start;
  assert.equal(await page.getByLabel('Full name', { exact: true }).inputValue(), 'Final QA');
  assert.equal(await page.getByLabel('Average nightly rate').inputValue(), '500');
  assert.ok(await page.evaluate(() => [...document.querySelectorAll('video')].every(v => v.paused)));
  for (const width of [320, 390, 768, 1024]) {
    await page.setViewportSize({ width, height: 844 });
    await page.goto('http://127.0.0.1:4173', { waitUntil: 'domcontentloaded' });
    await page.locator('.preloader').waitFor({ state: 'detached', timeout: 6000 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
    if (width === 390) {
      await page.screenshot({ path: 'test-results/lavilla-home-mobile.png' });
      await page.getByRole('button', { name: 'Open menu', exact: true }).click();
      await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'The residence' }).click();
      await page.waitForTimeout(100);
      assert.equal(await page.evaluate(() => location.hash), '#interior');
      await page.screenshot({ path: 'test-results/lavilla-interior-mobile.png' });
    }
  }
  // Run the full animation on mobile too, rather than checking only reduced motion.
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('http://127.0.0.1:4173', { waitUntil: 'domcontentloaded' });
  await page.locator('.preloader').waitFor({ state: 'visible' });
  await page.waitForTimeout(2650);
  const words = await page.locator('.welcome-word').evaluateAll(nodes => nodes.map(n => Number(getComputedStyle(n).opacity)));
  assert.ok(words.every(v => v > .95), 'All three welcome words visible during hold');
  await page.screenshot({ path: 'test-results/lavilla-preloader-mobile.png' });
  await page.locator('.preloader').waitFor({ state: 'detached', timeout: 6000 });
  await page.waitForTimeout(1600);
  await page.getByRole('link', { name: 'Step inside', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('main').dataset.transitioning === 'false');
  await page.waitForTimeout(200);
  assert.ok(await page.evaluate(() => scrollY > 400));
  assert.equal(await page.locator('#interior video').evaluate(v => getComputedStyle(v).transform), 'none');
  assert.deepEqual(errors, []); assert.deepEqual(failed, []);
  const report = { project: 'Lavilla Realstate', passed: true, errors, failed, viewports: [320, 390, 768, 1024, 1440], reducedLoadMs, checked: ['unchanged logo and video asset hashes verified separately', 'independent Home and Interior sections', 'autoplay at 0.65x', 'offscreen video pausing', 'both sections wait for outgoing animation before advancing', 'mobile video has no scroll transforms', 'no playback controls or timeline bar', 'preloader unmount and scroll restoration', 'word reveal and mobile loader', 'scroll navigation and section animations', 'responsive overflow', 'reduced motion posters', 'mobile menu', 'form and calculator persistence', 'inquiry saving', 'overview download', 'modal dismissal'] };
  fs.writeFileSync('VERIFICATION.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }

